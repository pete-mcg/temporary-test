import json
from langgraph.graph import StateGraph
from langchain_core.messages import AIMessage, AIMessageChunk
import logging


def _graph_state_to_dict(state: dict) -> dict:
    """
    Build a dictionary copy of the graph state. This is needed for logging to CosmosDB.
    (Can't use the graph state directly, as the "messages" key contains BaseMessage objects that need to be converted into dicts.)
    """
    graph_state = {}
    for key, value in state.items():
        if key == "messages":
            graph_state[key] = [
                {
                    "type": msg.__class__.__name__,
                    "content": msg.content,
                    "response_metadata": msg.response_metadata,
                }
                for msg in value
            ]
        else:
            graph_state[key] = value
    return graph_state


def annex_stream(graph: StateGraph, mp_name_list: str, question: str):
    """
    Streaming response using graph.astream().

    Arguments:
        graph (StateGraph): The LangGraph StateGraph instance representing the workflow.
        mp_name_list (str): The name of the MP, used as input to the graph.
        question (str): The question to be answered about the MP, used as input to the graph.

    Yields:
        str: A JSON string containing the latest chunk of the response content, formatted for streaming to the client.

    Return:
        dict: A dictionary representation of the final graph state after execution, for logging purposes.
    """

    result_holder = {"full_text": "", "graph_state": {}}

    async def generate():
        full_text = ""
        last_state = {}
        try:
            async for event_type, event_data in graph.astream(
                {"mp_name_list": mp_name_list, "mp_question": question},
                stream_mode=["messages", "values"],
            ):
                if event_type == "values":
                    # Capture the latest state snapshot (emitted after each node)
                    last_state = event_data

                elif event_type == "messages":
                    message_chunk, metadata = event_data
                    # Stream only AIMessageChunk content from 'generate_response' node.
                    if metadata.get(
                        "langgraph_node"
                    ) == "generate_response" and isinstance(
                        message_chunk, (AIMessageChunk, AIMessage)
                    ):
                        content = getattr(message_chunk, "content", "")
                        if content:
                            full_text += content
                            yield json.dumps(
                                {
                                    "choices": [
                                        {
                                            "messages": [
                                                {
                                                    "role": "assistant",
                                                    "content": content,
                                                }
                                            ]
                                        }
                                    ]
                                }
                            ) + "\n"

        except Exception as e:
            logging.exception("LangGraph streaming error")
            yield json.dumps({"error": str(e)}) + "\n"

        result_holder["full_text"] = full_text
        result_holder["graph_state"] = _graph_state_to_dict(last_state)

    return generate(), result_holder


async def annex_non_stream(graph: StateGraph, mp_name_list: str, question: str):
    """
    Non-streaming response using graph.ainvoke().

    Arguments:
        graph (StateGraph): The LangGraph StateGraph instance representing the workflow.
        mp_name_list (str): The name of the MP, used as input to the graph.
        question (str): The question to be answered about the MP, used as input to the graph.

    Return:
        str: The full response content generated by the graph.
        dict: A dictionary representation of the final graph state after execution, for logging purposes.
    """

    result = await graph.ainvoke(
        {"mp_name_list": mp_name_list, "mp_question": question}
    )
    messages = result.get("messages", [])
    response_content = messages[-1].content if messages else "No response generated."

    return response_content, _graph_state_to_dict(result)
